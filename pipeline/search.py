import concurrent.futures
import re

from .common import YT_DLP, run

CANDIDATES = 8

# (regex, score) applied to the video title; higher score = better pick for audio-only listening.
_TITLE_RULES = [
    (r"official audio|\(audio\)|\baudio\b|\blyrics?\b|lyric video", 3),
    (r"official (music )?video|music video|\bm/?v\b|official visualizer", -4),
    (r"\blive\b|concert|\bcover\b|remix|karaoke|reaction|tutorial|instrumental", -5),
    (r"sped up|slowed|reverb|8d|nightcore|bass boosted|\b1 hour\b|\bloop\b", -6),
]


def _score(channel, title, duration, median, artist=""):
    score = 0
    channel, title = channel or "", (title or "").lower()
    if artist and artist not in channel.lower() and artist not in title:
        score -= 8  # probably a different artist's version
    if channel.endswith("- Topic"):  # auto-generated by YouTube: pure audio, no intro
        score += 6
    for pattern, points in _TITLE_RULES:
        if re.search(pattern, title):
            score += points
    try:  # prefer the length most candidates agree on
        if abs(float(duration) - median) > 15:
            score -= 3
    except (TypeError, ValueError):
        pass
    return score


def youtube_search(query, cancel=None):
    """Return the best-suited YouTube URL for `query` (audio-friendly), or None."""
    result = run(
        [
            YT_DLP,
            f"ytsearch{CANDIDATES}:{query} audio",
            "--flat-playlist",
            "--print", "%(url)s\t%(channel)s\t%(title)s\t%(duration)s",
            "--quiet",
            "--no-warnings",
        ],
        cancel=cancel,
    )
    if result.returncode != 0:
        return None

    rows = []
    for line in result.stdout.splitlines():
        parts = line.rstrip("\n").split("\t")
        if len(parts) == 4 and parts[0].startswith("http"):
            rows.append(parts)
    if not rows:
        return None

    durations = sorted(float(r[3]) for r in rows if r[3].replace(".", "", 1).isdigit())
    median = durations[len(durations) // 2] if durations else 0
    artist = query.split(" - ", 1)[0].strip().lower() if " - " in query else ""

    # max() returns the first of equal scores, so YouTube's own ranking breaks ties.
    return max(rows, key=lambda r: _score(r[1], r[2], r[3], median, artist))[0]


def search_all(songs, on_result=None, cancel=None):
    """Search every song in parallel.

    Returns [(song, url_or_None), ...] in input order.
    `on_result(song, url)` is called as each search finishes.
    """
    results = [(s, None) for s in songs]

    def work(i):
        try:
            url = youtube_search(songs[i], cancel)
        except Exception:  # noqa: BLE001
            url = None
        results[i] = (songs[i], url)
        if on_result:
            on_result(songs[i], url)

    with concurrent.futures.ThreadPoolExecutor(max_workers=10) as ex:
        list(ex.map(work, range(len(songs))))
    return results
